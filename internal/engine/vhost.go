// This file holds the read-only renderer for a site's server block and the
// writer for the generated per-site files. It is the contract consumed by the
// `site` action (`op: config`) and by the Sites detail view: the text produced
// here is deliberately unchanged, and no external process is involved.

var (
	vhostSiteNameRE = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$`)
	domainRE        = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)*$`)
)

// vhostSite is one parked site rendered as a server block. Domains are extra
// server_name aliases; the canonical Name always comes first.
//
// Enabled=false keeps the site registered in config.json but removes its
// server block from the generated tree. RootState is "ok", "empty" or
// "missing"; anything other than "ok" makes the block serve the built-in
// not-configured status page instead of proxying to PHP-FPM. PagesDir points
// at <LAIR_HOME>/web/nginx/pages (relative "pages" is used when empty).
type vhostSite struct {
	Name      string
	Root      string
	PHPSocket string
	Cert      string
	Key       string
	Domains   []string
	Enabled   bool
	RootState string
	PagesDir  string
	// PHP and PHPInstalled drive the "install PHP" link on the status page.
	PHP          string
	PHPInstalled bool
}

// notConfiguredFile is the built-in status page served when a site has no
// front controller yet.
const notConfiguredFile = "not-configured.html"

// vhostRoot is the directory holding generated per-site files. The path is
// kept for compatibility with existing installations and UI previews.
func vhostRoot(root string) string { return filepath.Join(root, "web", "nginx") }

func vhostDir(root string) string      { return filepath.Join(vhostRoot(root), "sites") }
func vhostPagesDir(root string) string { return filepath.Join(vhostRoot(root), "pages") }

// renderVHost renders one server block with the current settings without
// touching disk. Disabled sites are rendered too, so the preview keeps working
// while a site is turned off.
func renderVHost(s config.WebSettings, site vhostSite) (string, error) {
	pages := site.PagesDir
	if pages == "" {
		// Server blocks resolve relative paths against vhostRoot.
		pages = "pages"
	}
	ready := site.RootState == "ok"
	root := q(filepath.Join(site.Root, "public"))
	index := "index.php index.html"
	locations := location()
	if !ready {
		root = q(pages)
		index = notConfiguredFile
		locations = notConfiguredLocation()
	}
	fastcgi := ""
	if ready {
		fastcgi = fastcgiLocation("  fastcgi_pass " + q("unix:"+site.PHPSocket) + ";\n" + fastcgiParams)
	}
	ssl := ""
	if s.HTTPS {
		if site.Cert == "" || site.Key == "" {
			return "", fmt.Errorf("site %s has no certificate for HTTPS", site.Name)
		}
		ssl = fmt.Sprintf(`
  ssl_certificate %s;
  ssl_certificate_key %s;
  ssl_protocols TLSv1.2 TLSv1.3;
  ssl_session_cache shared:SSL:1m;
  ssl_session_timeout 5m;
`, q(site.Cert), q(site.Key))
	}

	var out strings.Builder
	serverName := serverNames(site)
	fmt.Fprintf(&out, "# generated by lair · %s", site.Name)
	if ready {
		out.WriteByte('\n')
	} else {
		fmt.Fprintf(&out, " · root %s (%s) not ready\n", site.Root, site.RootState)
	}
	fmt.Fprintf(&out, "server {\n  listen %s:%d;\n  server_name %s;\n  root %s;\n  index %s;\n",
		s.Bind, s.HTTPPort, serverName, root, index)
	// A site without a front controller serves the status page on both
	// protocols: redirecting HTTP to HTTPS here would hide the diagnostic
	// behind an untrusted local CA.
	if s.HTTPS && s.RedirectHTTP && ready {
		port := ""
		if s.HTTPSPort != 443 {
			port = ":" + strconv.Itoa(s.HTTPSPort)
		}
		fmt.Fprintf(&out, "  return 301 https://$host%s$request_uri;\n", port)
	} else {
		out.WriteString(locations)
		out.WriteString(fastcgi)
	}
	out.WriteString("}\n")

	if s.HTTPS {
		fmt.Fprintf(&out, "\nserver {\n  listen %s:%d ssl;\n  server_name %s;\n  root %s;\n  index %s;\n%s",
			s.Bind, s.HTTPSPort, serverName, root, index, ssl)
		out.WriteString(locations)
		out.WriteString(fastcgi)
		out.WriteString("}\n")
	}
	return out.String(), nil
}

// notConfiguredLocation serves the built-in status page over both HTTP and
// HTTPS. There is deliberately no FastCGI block: until a front controller
// exists there is nothing for PHP-FPM to execute.
func notConfiguredLocation() string {
	return `
    location = / {
      try_files /` + notConfiguredFile + ` =404;
    }
    location / {
      try_files $uri =404;
    }
    location ~ /\.(?!well-known).* { deny all; }
`
}

// notConfiguredHTML builds the shared status page. The host is filled in at
// runtime from location.host; the list below gives the concrete expected path
// of every site that is registered but not ready yet.
func notConfiguredHTML(sites []vhostSite) string {
	var rows strings.Builder
	for _, site := range sites {
		if !site.Enabled || site.RootState == "ok" {
			continue
		}
		expected := filepath.Join(site.Root, "public", "index.php")
		fmt.Fprintf(&rows, "      <li><strong>%s</strong> &rarr; <code>%s</code></li>\n",
			html.EscapeString(site.Name), html.EscapeString(expected))
		if !site.PHPInstalled && site.PHP != "" {
			minor := html.EscapeString(strings.SplitN(site.PHP, ".", 2)[0])
			fmt.Fprintf(&rows, "      <li><strong>%s</strong> &rarr; <a href=\"lair://install/php/%s\" onclick=\"return confirm('Install PHP %s?')\">Install PHP %s</a></li>\n",
				html.EscapeString(site.Name), minor, minor, minor)
		}
	}
	if rows.Len() == 0 {
		rows.WriteString("      <li>Crea <code>public/index.php</code> en la raíz del proyecto.</li>\n")
	}
	return `<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Sitio no configurado</title>
<style>
body{font:16px/1.6 system-ui,sans-serif;max-width:52rem;margin:4rem auto;padding:0 1rem;color:#222}
h1{margin-bottom:.4rem}h2{margin-top:2rem}code{background:#f2f2f2;padding:.1rem .35rem;border-radius:4px}
</style>
</head>
<body>
<h1>Sitio no configurado</h1>
<p>Este host está registrado en Lair, pero todavía no tiene una aplicación PHP accesible.</p>
<p>Host: <strong id="lair-host">—</strong></p>
<p>Ruta esperada: <code>&lt;raíz del proyecto&gt;/public/index.php</code></p>
<h2>Sitios pendientes</h2>
<ul>
` + rows.String() + `</ul>
<p>Crea el archivo <code>public/index.php</code> en la raíz del proyecto y vuelve a cargar la página.</p>
<script>document.getElementById('lair-host').textContent=location.host;</script>
</body>
</html>
`
}

// serverNames builds the canonical host, its www alias and every configured
// alias, dropping duplicates. Values are validated in writeVHosts before render.
func serverNames(site vhostSite) string {
	seen := map[string]bool{}
	names := []string{}
	for _, name := range append([]string{site.Name, "www." + site.Name}, site.Domains...) {
		name = strings.ToLower(strings.TrimSuffix(strings.TrimSpace(name), "."))
		if name == "" || seen[name] {
			continue
		}
		seen[name] = true
		names = append(names, name)
	}
	return strings.Join(names, " ")
}

// writeVHosts writes the generated per-site files atomically. It validates
// every value before writing so a bad port or site name cannot produce a
// broken file, and drops blocks of sites that were unlinked since last time.
func writeVHosts(root string, s config.WebSettings, sites []vhostSite) error {
	for _, site := range sites {
		// Disabled sites are not rendered, so their (possibly stale) socket
		// and root do not need to be valid. Only the name is used for cleanup.
		if !site.Enabled {
			continue
		}
		if !vhostSiteNameRE.MatchString(site.Name) {
			return fmt.Errorf("invalid site name %q", site.Name)
		}
		if site.Root == "" || site.PHPSocket == "" {
			return fmt.Errorf("site %s is missing root or PHP socket", site.Name)
		}
		for _, alias := range site.Domains {
			if len(alias) > 253 || !domainRE.MatchString(alias) {
				return fmt.Errorf("invalid domain %q for site %s", alias, site.Name)
			}
		}
	}
	dir := vhostDir(root)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	pages := vhostPagesDir(root)
	if err := os.MkdirAll(pages, 0o755); err != nil {
		return err
	}
	if err := writeFile(filepath.Join(pages, notConfiguredFile), notConfiguredHTML(sites)); err != nil {
		return err
	}

	names := make([]string, 0, len(sites))
	for _, site := range sites {
		if !site.Enabled {
			continue
		}
		if site.PagesDir == "" {
			site.PagesDir = pages
		}
		body, err := renderVHost(s, site)
		if err != nil {
			return err
		}
		path := filepath.Join(dir, site.Name+".conf")
		if err := writeFile(path, body); err != nil {
			return err
		}
		names = append(names, site.Name)
	}
	// Drop configs of sites that were unlinked since the last generation.
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	keep := map[string]bool{}
	for _, name := range names {
		keep[name+".conf"] = true
	}
	for _, entry := range entries {
		if !keep[entry.Name()] && strings.HasSuffix(entry.Name(), ".conf") {
			_ = os.Remove(filepath.Join(dir, entry.Name()))
		}
	}
	return nil
}

func location() string {
	return `
  location / {
    try_files $uri $uri/ /index.php?$query_string;
  }
  location ~ /\.(?!well-known).* { deny all; }
`
}

func fastcgiLocation(params string) string {
	return `
  location ~ \.php$ {
    try_files $uri =404;
` + params + `  }
`
}

const fastcgiParams = `    fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
    fastcgi_param QUERY_STRING $query_string;
    fastcgi_param REQUEST_METHOD $request_method;
    fastcgi_param CONTENT_TYPE $content_type;
    fastcgi_param CONTENT_LENGTH $content_length;
    fastcgi_param SCRIPT_NAME $fastcgi_script_name;
    fastcgi_param REQUEST_URI $request_uri;
    fastcgi_param DOCUMENT_URI $document_uri;
    fastcgi_param DOCUMENT_ROOT $document_root;
    fastcgi_param SERVER_PROTOCOL $server_protocol;
    fastcgi_param GATEWAY_INTERFACE CGI/1.1;
    fastcgi_param SERVER_SOFTWARE nginx;
    fastcgi_param REMOTE_ADDR $remote_addr;
    fastcgi_param REMOTE_PORT $remote_port;
    fastcgi_param SERVER_ADDR $server_addr;
    fastcgi_param SERVER_PORT $server_port;
    fastcgi_param SERVER_NAME $server_name;
    fastcgi_param PATH_INFO $fastcgi_path_info;
    fastcgi_param HTTPS $https if_not_empty;
`

// q quotes a path for a generated directive.
func q(value string) string {
	value = strings.ReplaceAll(value, `\`, `\\`)
	value = strings.ReplaceAll(value, `"`, `\"`)
	return `"` + value + `"`
}

func writeFile(path, body string) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".lair-vhost-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if _, err := tmp.WriteString(body); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}
