package platform

import (
	"fmt"
	"path/filepath"
	"strings"
)

// normalizeDomain validates a DNS search domain before it becomes part of an
// absolute /etc/resolver path or a hosts-file entry.
func normalizeDomain(domain string) (string, error) {
	d := strings.ToLower(strings.Trim(strings.TrimSpace(domain), "."))
	if d == "" {
		return "", fmt.Errorf("empty DNS domain")
	}
	for _, label := range strings.Split(d, ".") {
		if label == "" {
			return "", fmt.Errorf("invalid DNS domain %q", domain)
		}
		for _, r := range label {
			if (r < 'a' || r > 'z') && (r < '0' || r > '9') && r != '-' {
				return "", fmt.Errorf("invalid DNS domain %q", domain)
			}
		}
	}
	return d, nil
}

// generateDarwin renders /etc/resolver/<domain>. Lair's embedded DNS server
// (internal/dns) already listens on 127.0.0.1:53535 on every OS, so no
// dnsmasq, systemd-resolved or launchd daemon is needed for name resolution.
func generateDarwin(cfg UnitConfig) (UnitFiles, error) {
	domain, err := normalizeDomain(cfg.Domain)
	if err != nil {
		return UnitFiles{}, err
	}
	return UnitFiles{
		ResolverPath: "/etc/resolver/" + domain,
		ResolverContent: fmt.Sprintf(
			"# Generated by Lair. *.%s -> Lair's embedded DNS.\n"+
				"nameserver 127.0.0.1\nport %d\n",
			domain, DefaultDNSPort),
	}, nil
}

// generateWindows renders a managed hosts-file block. Windows has no
// /etc/resolver equivalent that can be written without changing the interface
// DNS globally, so explicit entries are safer and fully reversible.
func generateWindows(cfg UnitConfig) (UnitFiles, error) {
	domain, err := normalizeDomain(cfg.Domain)
	if err != nil {
		return UnitFiles{}, err
	}
	seen := map[string]bool{}
	names := []string{}
	add := func(name string) {
		name = strings.ToLower(strings.Trim(strings.TrimSpace(name), "."))
		if name == "" || seen[name] || strings.ContainsAny(name, " \t\r\n/\\") {
			return
		}
		seen[name] = true
		names = append(names, name)
	}
	for _, host := range cfg.Hosts {
		add(host)
	}
	if len(names) == 0 {
		return UnitFiles{}, fmt.Errorf("no host names supplied for the Windows hosts plan")
	}
	var block strings.Builder
	block.WriteString("# BEGIN LAIR · *.test\n")
	for _, name := range names {
		fmt.Fprintf(&block, "127.0.0.1 %s\n", name)
	}
	block.WriteString("# END LAIR")
	return UnitFiles{
		HostsPath:  `C:\Windows\System32\drivers\etc\hosts`,
		HostsBlock: block.String(),
		ResolverContent: fmt.Sprintf(
			"# Generated by Lair. Domain: %s. Managed hosts: %d\n",
			domain, len(names)),
	}, nil
}

func psQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}

// powershellScript renders the Windows one-time plan. It backs up the hosts
// file, removes only Lair's managed block, appends the new block and installs
// the local CA in the Root store. No daemon service is created: Lair runs as
// the current user on Windows too.
func (p *PrivilegedPlan) powershellScript() string {
	backupDir := filepath.Join(p.backupDir)
	var s strings.Builder
	s.WriteString("# Generated by Lair. Review before running in an elevated PowerShell.\n")
	s.WriteString("$ErrorActionPreference = 'Stop'\n")
	if p.Files.HostsBlock != "" {
		fmt.Fprintf(&s, "$hostsFile = %s\n", psQuote(p.Files.HostsPath))
		fmt.Fprintf(&s, "$backupDir = %s\n", psQuote(backupDir))
		s.WriteString("New-Item -ItemType Directory -Force -Path $backupDir | Out-Null\n")
		s.WriteString("Copy-Item $hostsFile (Join-Path $backupDir (\"hosts.\" + (Get-Date -Format yyyyMMddHHmmss))) -Force\n")
		s.WriteString("$kept = @()\n$skip = $false\n")
		s.WriteString("foreach ($line in (Get-Content $hostsFile)) {\n")
		s.WriteString("  if ($line -like '# BEGIN LAIR*') { $skip = $true; continue }\n")
		s.WriteString("  if ($skip -and $line -like '# END LAIR*') { $skip = $false; continue }\n")
		s.WriteString("  if (-not $skip) { $kept += $line }\n}\n")
		s.WriteString("$block = @'\n" + p.Files.HostsBlock + "\n'@\n")
		s.WriteString("$kept += $block\n")
		s.WriteString("Set-Content -Path $hostsFile -Value $kept -Encoding ASCII\n")
	}
	if p.CAPath != "" {
		fmt.Fprintf(&s, "certutil -addstore -f Root %s\n", psQuote(p.CAPath))
	}
	return s.String()
}
