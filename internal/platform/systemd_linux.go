//go:build linux

package platform

import (
	"fmt"
	"path/filepath"
	"strings"
)

const unitName = "lair@.service"

// generateSystemd renders the systemd unit, the per-instance drop-in, the
// polkit rule and the systemd-resolved drop-in. All paths are absolute and
// every listener stays on loopback.
func generateSystemd(cfg UnitConfig) (UnitFiles, error) {
	if cfg.User == "" || cfg.ExecPath == "" || cfg.DataDir == "" {
		return UnitFiles{}, fmt.Errorf("user, exec path and data dir are required")
	}
	if !strings.HasPrefix(cfg.ExecPath, "/") || !strings.HasPrefix(cfg.DataDir, "/") {
		return UnitFiles{}, fmt.Errorf("exec path and data dir must be absolute")
	}
	if cfg.Domain == "" {
		cfg.Domain = "test"
	}
	// The legacy `#` form is what older Lair releases wrote. The safe dnsmasq
	// setup uses the `address:port` form of systemd-resolved.
	dnsAddress := strings.Replace(cfg.DNSAddress, "#", ":", 1)
	if dnsAddress == "" {
		dnsAddress = fmt.Sprintf("127.0.0.1:%d", DefaultDNSPort)
	}
	// Both the dnsmasq route and the fallback must use the modern
	// "address:port" syntax: systemd-resolved 259 ignores the legacy
	// "address#port" form, which left *.test unresolved on machines without
	// dnsmasq (the fallback is served by the daemon's embedded DNS server).
	fallbackAddress := dnsAddress

	unit := fmt.Sprintf(`[Unit]
Description=Lair development environment for %%i
After=network.target

[Service]
Type=simple
User=%%i
Group=%%i
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
NoNewPrivileges=yes
ProtectHome=no
Restart=always
RestartSec=2s
ExecStart=%s daemon --foreground
ExecReload=/bin/kill -HUP $MAINPID
KillMode=process
TimeoutStopSec=15s

[Install]
WantedBy=multi-user.target
`, cfg.ExecPath)

	dropIn := fmt.Sprintf(`# Generated by Lair. Per-instance environment.
[Service]
Environment=HOME=%s
Environment=LAIR_HOME=%s
Environment=PATH=%s/bin:/usr/local/bin:/usr/bin:/bin
`, cfg.Home, cfg.DataDir, cfg.DataDir)

	polkit := `// Generated by Lair. Let a user control only their own lair@<user> unit.
polkit.addRule(function(action, subject) {
    if (action.id == "org.freedesktop.systemd1.manage-units" &&
        action.lookup("unit") &&
        /^lair@.+\.service$/.test(action.lookup("unit"))) {
        var unit = action.lookup("unit");
        var expected = "lair@" + subject.user + ".service";
        if (unit == expected) {
            return polkit.Result.YES;
        }
    }
    return polkit.Result.NOT_HANDLED;
});
`

	resolved := fmt.Sprintf(`# Generated by Lair. Route *.%s to the local DNS server.
[Resolve]
DNS=%s
Domains=~%s
`, cfg.Domain, dnsAddress, cfg.Domain)
	fallback := fmt.Sprintf(`# Generated by Lair. Fallback when dnsmasq cannot run.
[Resolve]
DNS=%s
Domains=~%s
`, fallbackAddress, cfg.Domain)

	// dnsmasq is bound to loopback on a high port only: it never listens on
	// the system-wide port 53 and never forwards anything itself (no-resolve).
	confPath := filepath.Join(cfg.DataDir, "dns", "dnsmasq.conf")
	dnsmasq := fmt.Sprintf(`# Generated by Lair. Safe local DNS for *.%s.
port=%d
listen-address=127.0.0.1
bind-interfaces
no-resolv
no-hosts
address=/%s/127.0.0.1
`, cfg.Domain, DefaultDNSPort, cfg.Domain)
	dnsUnit := fmt.Sprintf(`[Unit]
Description=Lair local DNS (dnsmasq)
After=network.target

[Service]
Type=simple
ExecStart=/usr/sbin/dnsmasq --keep-in-foreground --conf-file=%s
Restart=on-failure
RestartSec=2s

[Install]
WantedBy=multi-user.target
`, confPath)

	return UnitFiles{
		UnitPath:                filepath.Join("/etc/systemd/system", unitName),
		UnitContent:             unit,
		DropInPath:              fmt.Sprintf("/etc/systemd/system/lair@%s.service.d/10-lair.conf", cfg.User),
		DropInContent:           dropIn,
		PolkitPath:              "/etc/polkit-1/rules.d/50-lair.rules",
		PolkitContent:           polkit,
		ResolvedPath:            ResolvedDropIn,
		ResolvedContent:         resolved,
		DnsmasqConfPath:         confPath,
		DnsmasqConfContent:      dnsmasq,
		DNSUnitPath:             "/etc/systemd/system/" + DNSUnitName,
		DNSUnitContent:          dnsUnit,
		FallbackResolvedContent: fallback,
	}, nil
}
