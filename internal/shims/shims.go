// Package shims creates the small shell wrappers in bin/ and maintains the
// shell profile snippets that put bin/ on PATH. Every operation is idempotent
// and reversible so `lair uninstall` can remove exactly what it added.
package shims

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// Tools is the set of commands exposed as shims.
var Tools = []string{
	"php", "php-fpm", "composer",
	"node", "npm", "npx",
	"psql", "pg_dump", "pg_restore", "createdb", "dropdb",
	"mysql", "mariadb", "mysqldump",
	"redis-cli", "valkey-cli",
	"mongosh", "sqlite3",
}

var toolRE = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*$`)

// validTool rejects shell metacharacters, whitespace and path separators in a
// shim tool name. Only the commands Lair ships may become shims.
func validTool(tool string) bool {
	if !toolRE.MatchString(tool) {
		return false
	}
	for _, known := range Tools {
		if tool == known {
			return true
		}
	}
	return false
}

// shellQuote returns a POSIX shell single-quoted literal. The only character
// needing special treatment is the single quote itself, which is emitted as
// the standard '"'"' sequence; everything else ($, `, \, spaces, newlines) is
// inert inside the quotes.
func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", `'"'"'`) + "'"
}

// ShimScript returns the contents of a shim. The hidden `exec` subcommand of
// lair resolves the right version for the current directory and execve's the
// real binary, replacing the shell process entirely. Both values are quoted,
// so even a hostile path coming from a payload cannot inject shell code.
func ShimScript(lairBinary, tool string) string {
	if !validTool(tool) {
		tool = ""
	}
	return fmt.Sprintf("#!/bin/sh\n# Generated by Lair. Do not edit.\nexec %s exec %s \"$@\"\n",
		shellQuote(lairBinary), shellQuote(tool))
}

// Generate writes every shim into binDir. Existing shims are overwritten so
// an upgrade updates the embedded lair path.
func Generate(binDir, lairBinary string) error {
	if err := os.MkdirAll(binDir, 0o755); err != nil {
		return err
	}
	for _, tool := range Tools {
		if !validTool(tool) {
			return fmt.Errorf("invalid shim tool %q", tool)
		}
		path := filepath.Join(binDir, tool)
		if err := os.WriteFile(path, []byte(ShimScript(lairBinary, tool)), 0o755); err != nil {
			return fmt.Errorf("shim %s: %w", tool, err)
		}
	}
	return nil
}

// List returns the shim names in a stable order.
func List() []string {
	out := append([]string(nil), Tools...)
	sort.Strings(out)
	return out
}
